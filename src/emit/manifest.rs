fn python_manifest(document: &Document, extended: bool) -> String {
    let json = if extended {
        emit_json(document)
    } else {
        rvmt_manifest_json(document)
    };
    json_to_python_literals(&json)
}

/// JSON is already Python apart from three literals -- but rewriting them with
/// a string replace rewrites them inside string *values* too, and the manifest
/// is full of prose: a rationale reading "holds true for a null count" came out
/// as "holds True for a None count". So this walks the document and rewrites
/// only what is outside a string.
fn json_to_python_literals(json: &str) -> String {
    let mut out = String::with_capacity(json.len());
    let mut rest = json;
    let mut in_string = false;
    let mut escaped = false;
    while let Some(ch) = rest.chars().next() {
        if in_string {
            out.push(ch);
            if escaped {
                escaped = false;
            } else if ch == '\\' {
                escaped = true;
            } else if ch == '"' {
                in_string = false;
            }
            rest = &rest[ch.len_utf8()..];
            continue;
        }
        if ch == '"' {
            in_string = true;
            out.push(ch);
            rest = &rest[1..];
            continue;
        }
        let mut rewritten = false;
        for (from, to) in [("true", "True"), ("false", "False"), ("null", "None")] {
            if rest.starts_with(from) {
                out.push_str(to);
                rest = &rest[from.len()..];
                rewritten = true;
                break;
            }
        }
        if !rewritten {
            out.push(ch);
            rest = &rest[ch.len_utf8()..];
        }
    }
    out
}

