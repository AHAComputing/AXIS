//! AXIS emit: manifest domain (split from the former monolithic emit.rs).

use super::common::*;

pub fn emit_json(document: &Document) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    line(&mut out, 1, "\"schema\": \"axis.manifest.v1\",");
    line(&mut out, 1, "\"legacy_schema\": \"pce-adl.manifest.v1\",");
    line(
        &mut out,
        1,
        &format!("\"name\": {},", json_string(&document.extension.name)),
    );
    line(
        &mut out,
        1,
        &format!("\"version\": {},", json_string(&document.extension.version)),
    );
    line(
        &mut out,
        1,
        &format!("\"target\": {},", json_string(&document.extension.target)),
    );
    line(
        &mut out,
        1,
        &format!(
            "\"description\": {},",
            json_string(&document.extension.description)
        ),
    );

    emit_isas_json(&mut out, document);
    out.push_str(",\n");
    emit_instructions_json(&mut out, document);
    out.push_str(",\n");
    emit_cores_json(&mut out, document);
    out.push_str(",\n");
    emit_accelerators_json(&mut out, document);
    out.push_str(",\n");
    emit_memories_json(&mut out, document);
    out.push_str(",\n");
    emit_tiles_json(&mut out, document);
    out.push_str(",\n");
    emit_abis_json(&mut out, document);
    emit_kernels_json(&mut out, document);
    emit_descriptors_json(&mut out, document);
    emit_devices_json(&mut out, document);
    // Both sections end with a comma -- tiles because a section follows it now,
    // abis because it writes one per entry -- and the last one in the object
    // must not. Trimming here rather than threading "am I last" through two
    // emitters keeps a document with no ABI byte-identical to what it emitted
    // before ABIs existed, which is the invariant asserted in tests/golden.rs.
    out.truncate(out.trim_end_matches([',', '\n']).len());
    out.push('\n');
    out.push_str("}\n");
    out
}

pub fn emit_python(document: &Document) -> String {
    let mut out = String::new();
    out.push_str("# Generated by AXIS. Data-only module; do not edit by hand.\n\n");
    out.push_str("AXIS_SCHEMA = \"axis.manifest.v1\"\n");
    out.push_str("PCE_ADL_SCHEMA = \"pce-adl.manifest.v1\"\n\n");
    out.push_str("RVMT_EXTENSION_MANIFEST = ");
    out.push_str(&python_manifest(document, false));
    out.push_str("\n\nPCE_ADL_MANIFEST = ");
    out.push_str(&python_manifest(document, true));
    out.push('\n');
    out
}

pub fn emit_rvmt_json(document: &Document) -> String {
    rvmt_manifest_json(document)
}

pub fn emit_bundle_manifest_json(document: &Document) -> String {
    let mut out = String::new();
    out.push_str("{\n");
    line(&mut out, 1, "\"schema\": \"axis.bundle-manifest.v1\",");
    line(&mut out, 1, "\"generator\": \"axis\",");
    line(
        &mut out,
        1,
        &format!(
            "\"generator_version\": {},",
            json_string(env!("CARGO_PKG_VERSION"))
        ),
    );
    // The commit, beside the version that cannot move. `generator_version` is
    // `0.1.0` and always has been, so an artifact carrying only it cannot tell
    // a consumer which AXIS produced it -- which is the question
    // `AXISMINE_BINARY_REGION_MINING.md` spent a diagnosis failing to ask. A
    // build from an uncommitted tree says `-dirty`, because "not any commit" is
    // the answer a reader most needs when an artifact disagrees with the repo.
    line(
        &mut out,
        1,
        &format!(
            "\"generator_build\": {},",
            json_string(option_env!("AXIS_BUILD").unwrap_or("unstamped"))
        ),
    );
    line(
        &mut out,
        1,
        &format!("\"name\": {},", json_string(&document.extension.name)),
    );
    line(
        &mut out,
        1,
        &format!("\"version\": {},", json_string(&document.extension.version)),
    );
    line(
        &mut out,
        1,
        &format!("\"target\": {},", json_string(&document.extension.target)),
    );
    line(&mut out, 1, "\"model\": {");
    line(&mut out, 2, &format!("\"isas\": {},", document.isas.len()));
    line(
        &mut out,
        2,
        &format!("\"instructions\": {},", document.instructions.len()),
    );
    line(
        &mut out,
        2,
        &format!("\"cores\": {},", document.cores.len()),
    );
    line(
        &mut out,
        2,
        &format!("\"accelerators\": {},", document.accelerators.len()),
    );
    line(
        &mut out,
        2,
        &format!("\"memories\": {},", document.memories.len()),
    );
    line(&mut out, 2, &format!("\"tiles\": {}", document.tiles.len()));
    line(&mut out, 1, "},");
    line(&mut out, 1, "\"artifacts\": [");
    for (idx, artifact) in bundle_artifacts().iter().enumerate() {
        let suffix = if idx + 1 == bundle_artifacts().len() {
            ""
        } else {
            ","
        };
        line(&mut out, 2, "{");
        line(
            &mut out,
            3,
            &format!("\"path\": {},", json_string(artifact.path)),
        );
        line(
            &mut out,
            3,
            &format!("\"kind\": {},", json_string(artifact.kind)),
        );
        line(
            &mut out,
            3,
            &format!("\"schema\": {},", json_string(artifact.schema)),
        );
        line(
            &mut out,
            3,
            &format!("\"compatibility\": {}", json_string(artifact.compatibility)),
        );
        line(&mut out, 2, &format!("}}{suffix}"));
    }
    line(&mut out, 1, "]");
    out.push_str("}\n");
    out
}

fn emit_isas_json(out: &mut String, document: &Document) {
    line(out, 1, "\"isas\": [");
    for (idx, isa) in document.isas.iter().enumerate() {
        line(out, 2, "{");
        line(out, 3, &format!("\"name\": {},", json_string(&isa.name)));
        if !isa.role.is_empty() {
            line(out, 3, &format!("\"role\": {},", json_string(&isa.role)));
        }
        line(out, 3, &format!("\"base\": {},", json_string(&isa.base)));
        line(out, 3, &format!("\"word_bits\": {},", isa.word_bits));
        line(
            out,
            3,
            &format!("\"registers\": {},", json_list(&isa.registers)),
        );
        line(
            out,
            3,
            &format!("\"features\": {},", json_list(&isa.features)),
        );
        line(
            out,
            3,
            &format!("\"memory_model\": {},", json_string(&isa.memory_model)),
        );
        line(
            out,
            3,
            &format!("\"endianness\": {}", json_string(&isa.endianness)),
        );
        let suffix = if idx + 1 == document.isas.len() {
            ""
        } else {
            ","
        };
        line(out, 2, &format!("}}{suffix}"));
    }
    write_indent(out, 1);
    out.push(']');
}

fn emit_instructions_json(out: &mut String, document: &Document) {
    let modelled = crate::hw::modelled_costs(document);
    line(out, 1, "\"instructions\": [");
    for (idx, instruction) in document.instructions.iter().enumerate() {
        line(out, 2, "{");
        line(
            out,
            3,
            &format!("\"name\": {},", json_string(&instruction.name)),
        );
        line(
            out,
            3,
            &format!("\"mnemonic\": {},", json_string(&instruction.mnemonic)),
        );
        if !instruction.isa.is_empty() {
            line(
                out,
                3,
                &format!("\"isa\": {},", json_string(&instruction.isa)),
            );
        }
        line(
            out,
            3,
            &format!(
                "\"description\": {},",
                json_string(&instruction.description)
            ),
        );
        line(
            out,
            3,
            &format!("\"category\": {},", json_string(&instruction.category)),
        );
        line(
            out,
            3,
            &format!("\"format\": {},", json_string(&instruction.format)),
        );
        line(out, 3, "\"decode_key\": {");
        line(out, 4, &format!("\"opcode\": {},", instruction.opcode));
        line(out, 4, &format!("\"func3\": {},", instruction.func3));
        line(out, 4, &format!("\"func7\": {}", instruction.func7));
        line(out, 3, "},");
        // A scalable instruction is one lane of an origin, and its operands
        // name *elements* rather than registers -- which is why an operand of
        // the base register class can be eight bits wide on a 64-bit machine
        // without contradicting anything. Nothing outside this crate could
        // tell those apart from a register named at the wrong width, so a
        // check for the latter had to guess from the mnemonic's `__l0` suffix
        // and mistook 247 legitimate element views for defects.
        //
        // Emitted only when there is one, so every document that describes no
        // scalable instruction keeps the artifact it had.
        if !instruction.scalable_origin.is_empty() {
            line(
                out,
                3,
                &format!(
                    "\"scalable_origin\": {},",
                    json_string(&instruction.scalable_origin)
                ),
            );
            line(
                out,
                3,
                &format!("\"scalable_lane\": {},", instruction.scalable_lane),
            );
        }
        // The kernel an instruction launches and the operands it binds to the
        // kernel's params, positionally -- only when there is one, so every
        // document without a kernel keeps the artifact it had.
        if let Some((kernel, arguments)) = instruction.runs_kernel.split_first() {
            let arguments: Vec<String> = arguments.iter().map(|a| json_string(a)).collect();
            line(
                out,
                3,
                &format!(
                    "\"runs_kernel\": {{\"name\": {}, \"arguments\": [{}]}},",
                    json_string(kernel),
                    arguments.join(", ")
                ),
            );
        }
        // The descriptor this instruction launches, the operand holding its
        // address, and the kernel with its arguments -- only when there is one.
        if let [descriptor, base, rest @ ..] = instruction.launches.as_slice() {
            let (kernel, arguments) = match rest.split_first() {
                Some((kernel, arguments)) => (json_string(kernel), arguments),
                None => ("null".to_string(), &[][..]),
            };
            let arguments: Vec<String> = arguments.iter().map(|a| json_string(a)).collect();
            line(
                out,
                3,
                &format!(
                    "\"launches\": {{\"descriptor\": {}, \"base\": {}, \"kernel\": {kernel}, \"arguments\": [{}]}},",
                    json_string(descriptor),
                    json_string(base),
                    arguments.join(", ")
                ),
            );
        }
        emit_operands_json(out, &instruction.operands, 3);
        out.push_str(",\n");
        line(
            out,
            3,
            &format!("\"asm\": {},", json_string(&instruction_asm(instruction))),
        );
        // A `modes` array only when the instruction is mode-restricted, so
        // mode-free documents stay byte-identical.
        if !instruction.modes.is_empty() {
            line(
                out,
                3,
                &format!("\"modes\": {},", json_list(&instruction.modes)),
            );
        }
        if !instruction.decode_requires.trim().is_empty() {
            line(
                out,
                3,
                &format!(
                    "\"decode_requires\": {},",
                    json_string(instruction.decode_requires.trim())
                ),
            );
        }
        line(
            out,
            3,
            &format!("\"semantics\": {},", json_string(&instruction.semantics)),
        );
        // manifest.json is what OptiSynth's rewrite-rule extraction parses
        // (adl_bridge._as_manifest), so this carries the OptiSynth dialect
        // when expressible; the raw AXIS form lives in semantics.json.
        let optisynth = optisynth_formal_semantics(instruction);
        line(
            out,
            3,
            &format!(
                "\"formal_semantics\": {},",
                json_string(
                    optisynth
                        .as_deref()
                        .unwrap_or(&instruction.formal_semantics)
                )
            ),
        );
        line(
            out,
            3,
            &format!(
                "\"optisynth_compatible\": {},",
                json_bool(optisynth.is_some())
            ),
        );
        line(
            out,
            3,
            &format!("\"latency_cycles\": {},", instruction.latency_cycles),
        );
        // The unit this issues to: the ISA's half of a linkage whose other
        // half is the machine's `defcore`.
        line(
            out,
            3,
            &format!("\"unit\": {},", json_string(&instruction.unit)),
        );
        line(
            out,
            3,
            &format!(
                "\"throughput_per_cycle\": {},",
                instruction.throughput_per_cycle
            ),
        );
        line(out, 3, "\"cost_model\": {");
        line(
            out,
            4,
            &format!("\"area_estimate_um2\": {},", instruction.area_estimate_um2),
        );
        line(
            out,
            4,
            &format!("\"power_estimate_mw\": {},", instruction.power_estimate_mw),
        );
        line(
            out,
            4,
            &format!("\"expected_speedup\": {},", instruction.expected_speedup),
        );
        // The three above are declared and unchecked; these are the
        // instruction's netlist under the calibrated model, null without one.
        line(out, 4, "\"declared\": true,");
        let (area, depth) = modelled.get(&instruction.mnemonic).copied().unzip();
        line(
            out,
            4,
            &format!(
                "\"area_model_um2\": {}, \"depth_model_gates\": {}",
                area.map_or("null".to_string(), |a| format!("{:.1}", a * crate::hw::NAND2_UM2)),
                depth.map_or("null".to_string(), |d| format!("{d:.1}"))
            ),
        );
        line(out, 3, "},");
        line(
            out,
            3,
            &format!("\"intrinsic\": {},", json_string(&instruction.intrinsic)),
        );
        line(
            out,
            3,
            &format!("\"patterns\": {},", json_list(&instruction.patterns)),
        );
        line(
            out,
            3,
            &format!(
                "\"applicable_patterns\": {},",
                json_list(&instruction.applicable_patterns)
            ),
        );
        line(
            out,
            3,
            &format!("\"rationale\": {}", json_string(&instruction.rationale)),
        );
        let suffix = if idx + 1 == document.instructions.len() {
            ""
        } else {
            ","
        };
        line(out, 2, &format!("}}{suffix}"));
    }
    write_indent(out, 1);
    out.push(']');
}

fn emit_cores_json(out: &mut String, document: &Document) {
    line(out, 1, "\"cores\": [");
    for (idx, core) in document.cores.iter().enumerate() {
        emit_core_json_object(out, core, 2, idx + 1 == document.cores.len());
    }
    write_indent(out, 1);
    out.push(']');
}

/// F1. The frame, with its **slot table computed** rather than left to a
/// consumer. The layout is a function of the save order, the slot size and
/// which end the saved area sits at; publishing the answer means one
/// derivation instead of one per reader, which is the argument
/// `mapping_manifest.json` makes for the modulo occupancy tables.
///
/// Offsets are relative to the frame base -- the stack pointer after the
/// adjustment -- and stated at `max_frame_bytes`, the one frame size a
/// description names. A consumer with a smaller frame slides the top-anchored
/// slots down by the difference; the *rule* it needs for that is
/// `saved_area`, which is published beside them.
fn emit_frame_json(out: &mut String, frame: &crate::ast::Frame, indent: usize) {
    line(out, indent, "\"frame\": {");
    line(out, indent + 1, &format!("\"growth\": {},", json_string(&frame.growth)));
    line(
        out,
        indent + 1,
        &format!("\"saved_area\": {},", json_string(&frame.saved_area)),
    );
    line(out, indent + 1, &format!("\"slot_bytes\": {},", frame.slot_bytes));
    line(
        out,
        indent + 1,
        &format!(
            "\"frame_pointer_at\": {},",
            json_string(&frame.frame_pointer_at)
        ),
    );
    line(
        out,
        indent + 1,
        &format!("\"max_frame_bytes\": {},", frame.max_frame_bytes),
    );
    line(out, indent + 1, &format!("\"red_zone\": {},", frame.red_zone));
    line(out, indent + 1, &format!("\"adjust\": {},", json_string(&frame.adjust)));
    line(out, indent + 1, &format!("\"save\": {},", json_string(&frame.save)));
    line(
        out,
        indent + 1,
        &format!("\"restore\": {},", json_string(&frame.restore)),
    );
    line(out, indent + 1, "\"slots\": [");
    let saved = frame.saved_registers();
    let count = saved.len();
    for (rank, (class, index)) in saved.iter().enumerate() {
        let comma = if rank + 1 == count { "" } else { "," };
        line(
            out,
            indent + 2,
            &format!(
                "{{\"register\": [{}, {index}], \"rank\": {rank}, \"offset\": {}}}{comma}",
                json_string(class),
                frame.slot(rank, frame.max_frame_bytes)
            ),
        );
    }
    line(out, indent + 1, "],");
    line(
        out,
        indent + 1,
        &format!("\"saved_bytes\": {},", frame.saved_bytes()),
    );
    // F4/F5. Regions carry no sizes -- see `frame_design.md` §7 for the line
    // that draws -- and the pointer discipline is published as declared, with
    // the implication between its three fields already decided by the
    // validator rather than left for a consumer to work out.
    line(
        out,
        indent + 1,
        &format!("\"regions\": {},", json_list(&frame.regions)),
    );
    line(out, indent + 1, "\"spill\": [");
    let count = frame.spill.len();
    for (index, slot) in frame.spill.iter().enumerate() {
        let comma = if index + 1 == count { "" } else { "," };
        line(
            out,
            indent + 2,
            &format!(
                "{{\"class\": {}, \"bytes\": {}, \"align\": {}}}{comma}",
                json_string(&slot.class),
                slot.bytes,
                slot.align
            ),
        );
    }
    line(out, indent + 1, "],");
    line(
        out,
        indent + 1,
        &format!("\"realignment\": {},", json_string(&frame.realignment)),
    );
    line(
        out,
        indent + 1,
        &format!(
            "\"dynamic_allocation\": {},",
            json_string(&frame.dynamic_allocation)
        ),
    );
    line(
        out,
        indent + 1,
        &format!(
            "\"base_pointer\": {}",
            abi_single_json(&frame.base_pointer)
        ),
    );
    line(out, indent, "},");
}

/// The registers of one role, as `[class, index]` pairs with ranges expanded.
/// Expanded on purpose: a consumer asking "what role does this register have"
/// should not have to re-implement range arithmetic, and the partition a gate
/// re-derives is over registers rather than over the ranges that named them.
fn abi_role_json(refs: &[crate::ast::RegisterRef]) -> String {
    let mut entries = Vec::new();
    for reference in refs {
        for index in reference.indices() {
            entries.push(format!("[{}, {index}]", json_string(&reference.class)));
        }
    }
    format!("[{}]", entries.join(", "))
}

fn abi_single_json(reference: &Option<crate::ast::RegisterRef>) -> String {
    match reference {
        Some(reference) => format!(
            "[{}, {}]",
            json_string(&reference.class),
            reference.first
        ),
        None => "null".to_string(),
    }
}

/// L4. The declared calling conventions. Emitted only when a document declares
/// one, so every manifest produced before ABIs existed stays byte-identical.
fn emit_abis_json(out: &mut String, document: &Document) {
    if document.abis.is_empty() {
        return;
    }
    line(out, 1, "\"abis\": [");
    let count = document.abis.len();
    for (index, abi) in document.abis.iter().enumerate() {
        line(out, 2, "{");
        line(out, 3, &format!("\"name\": {},", json_string(&abi.name)));
        line(out, 3, &format!("\"isa\": {},", json_string(&abi.isa)));
        line(out, 3, &format!("\"pointer_bits\": {},", abi.pointer_bits));
        line(
            out,
            3,
            &format!("\"stack_alignment\": {},", abi.stack_alignment),
        );
        line(
            out,
            3,
            &format!("\"stack_pointer\": {},", abi_single_json(&abi.stack_pointer)),
        );
        line(
            out,
            3,
            &format!("\"frame_pointer\": {},", abi_single_json(&abi.frame_pointer)),
        );
        line(
            out,
            3,
            &format!(
                "\"link_register\": {},",
                abi_single_json(&abi.link_register)
            ),
        );
        line(
            out,
            3,
            &format!("\"arguments\": {},", abi_role_json(&abi.arguments)),
        );
        line(out, 3, &format!("\"returns\": {},", abi_role_json(&abi.returns)));
        line(
            out,
            3,
            &format!("\"callee_saved\": {},", abi_role_json(&abi.callee_saved)),
        );
        line(
            out,
            3,
            &format!("\"caller_saved\": {},", abi_role_json(&abi.caller_saved)),
        );
        line(
            out,
            3,
            &format!("\"reserved\": {},", abi_role_json(&abi.reserved)),
        );
        if let Some(frame) = &abi.frame {
            emit_frame_json(out, frame, 3);
        }
        if let Some(aggregates) = &abi.aggregates {
            line(out, 3, "\"aggregates\": {");
            line(
                out,
                4,
                &format!(
                    "\"max_register_bytes\": {},",
                    aggregates.max_register_bytes
                ),
            );
            line(
                out,
                4,
                &format!("\"split\": {},", json_string(&aggregates.split)),
            );
            line(
                out,
                4,
                &format!(
                    "\"return_pointer\": {}",
                    abi_single_json(&aggregates.return_pointer)
                ),
            );
            line(out, 3, "},");
        }
        line(
            out,
            3,
            &format!("\"description\": {}", json_string(&abi.description)),
        );
        line(out, 2, if index + 1 == count { "}" } else { "}," });
    }
    line(out, 1, "],");
}

/// A kernel's name, params and iteration space -- what a scheduler or a
/// compiler needs to know about the work without reading its body. Written
/// only when there is a kernel, and with a trailing comma like `abis`, so the
/// trim in `emit_json` treats it as it treats every other last section.
fn emit_kernels_json(out: &mut String, document: &Document) {
    if document.kernels.is_empty() {
        return;
    }
    line(out, 1, "\"kernels\": [");
    for (index, kernel) in document.kernels.iter().enumerate() {
        let params: Vec<String> = kernel.params.iter().map(|p| json_string(p)).collect();
        let space: Vec<String> = kernel
            .space
            .iter()
            .map(|(name, extent)| format!("{{\"index\": {}, \"extent\": {extent}}}", json_string(name)))
            .collect();
        let launchers: Vec<String> = document
            .instructions
            .iter()
            .filter(|i| i.runs_kernel.first() == Some(&kernel.name))
            .map(|i| json_string(&i.name))
            .collect();
        line(out, 2, "{");
        line(out, 3, &format!("\"name\": {},", json_string(&kernel.name)));
        line(out, 3, &format!("\"params\": [{}],", params.join(", ")));
        line(out, 3, &format!("\"space\": [{}],", space.join(", ")));
        line(out, 3, &format!("\"launched_by\": [{}],", launchers.join(", ")));
        line(out, 3, &format!("\"description\": {}", json_string(&kernel.description)));
        line(out, 2, if index + 1 == document.kernels.len() { "}" } else { "}," });
    }
    line(out, 1, "],");
}

/// Each descriptor's layout, checks and status, and the instructions that
/// launch it: what AHA's loader knew as `descriptor_schema` and
/// `descriptor_bytes` alone. Written only when there is one.
fn emit_descriptors_json(out: &mut String, document: &Document) {
    if document.descriptors.is_empty() {
        return;
    }
    line(out, 1, "\"descriptors\": [");
    for (index, descriptor) in document.descriptors.iter().enumerate() {
        let fields: Vec<String> = descriptor
            .fields
            .iter()
            .map(|field| {
                format!(
                    "{{\"name\": {}, \"offset\": {}, \"width\": {}, \"signed\": {}}}",
                    json_string(&field.name),
                    field.offset,
                    field.width,
                    field.signed
                )
            })
            .collect();
        let checks: Vec<String> = descriptor
            .checks
            .iter()
            .map(|check| {
                format!(
                    "{{\"condition\": {}, \"status\": {}}}",
                    json_string(&check.condition),
                    check.status
                )
            })
            .collect();
        let launchers: Vec<String> = document
            .instructions
            .iter()
            .filter(|i| i.launches.first() == Some(&descriptor.name))
            .map(|i| json_string(&i.name))
            .collect();
        line(out, 2, "{");
        line(out, 3, &format!("\"name\": {},", json_string(&descriptor.name)));
        line(out, 3, &format!("\"bytes\": {},", descriptor.bytes));
        line(out, 3, &format!("\"fields\": [{}],", fields.join(", ")));
        line(out, 3, &format!("\"checks\": [{}],", checks.join(", ")));
        line(
            out,
            3,
            &format!(
                "\"status\": {{\"field\": {}, \"returned\": {}, \"width\": {}, \"success\": 0}},",
                if descriptor.status_field.is_empty() {
                    "null".to_string()
                } else {
                    json_string(&descriptor.status_field)
                },
                descriptor.status_field.is_empty(),
                descriptor.status_width
            ),
        );
        line(out, 3, &format!("\"launched_by\": [{}],", launchers.join(", ")));
        line(out, 3, &format!("\"description\": {}", json_string(&descriptor.description)));
        line(out, 2, if index + 1 == document.descriptors.len() { "}" } else { "}," });
    }
    line(out, 1, "],");
}

/// Each MMIO device's window and register map: the offset, the direction and
/// the handler that runs. Written only when there is one.
fn emit_devices_json(out: &mut String, document: &Document) {
    if document.devices.is_empty() {
        return;
    }
    line(out, 1, "\"devices\": [");
    for (index, device) in document.devices.iter().enumerate() {
        let registers: Vec<String> = device
            .registers
            .iter()
            .map(|r| {
                format!(
                    "{{\"offset\": {}, \"access\": {}, \"handler\": {}}}",
                    r.offset,
                    json_string(&r.access),
                    json_string(&r.handler)
                )
            })
            .collect();
        line(out, 2, "{");
        line(out, 3, &format!("\"name\": {},", json_string(&device.name)));
        line(out, 3, &format!("\"isa\": {},", json_string(&device.isa)));
        line(out, 3, &format!("\"window\": {},", device.window));
        line(out, 3, &format!("\"registers\": [{}],", registers.join(", ")));
        line(out, 3, &format!("\"description\": {}", json_string(&device.description)));
        line(out, 2, if index + 1 == document.devices.len() { "}" } else { "}," });
    }
    line(out, 1, "],");
}

