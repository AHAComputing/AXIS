def find_tblgen():
    import os
    for var in ("AXIS_LLVM_TBLGEN",):
        if os.environ.get(var):
            return Path(os.environ[var])
    found = shutil.which("llvm-tblgen")
    if found:
        return Path(found)
    for prefix in BREW:
        candidate = Path(prefix) / "bin" / "llvm-tblgen"
        if candidate.exists():
            return candidate
    return None


def find_include():
    import os
    if os.environ.get("AXIS_LLVM_INCLUDE"):
        return Path(os.environ["AXIS_LLVM_INCLUDE"])
    for prefix in BREW:
        candidate = Path(prefix) / "include"
        if (candidate / "llvm" / "Target" / "Target.td").exists():
            return candidate
    return None


def run(cmd, **kwargs):
    return subprocess.run(cmd, capture_output=True, text=True, **kwargs)


def axis(args, out):
    result = run([*axis_prefix()] + args + ["-o", str(out)], cwd=ROOT)
    if result.returncode != 0:
        raise SystemExit(f"axis {' '.join(args)} failed: {result.stderr[:400]}")


def tablegen(tb, inc, td, kind, out):
    with open(out, "w") as handle:
        result = subprocess.run(
            [str(tb), f"--{kind}", "-I", str(inc), str(td)],
            stdout=handle, stderr=subprocess.PIPE, text=True)
    if result.returncode != 0:
        raise SystemExit(f"llvm-tblgen --{kind} failed:\n{result.stderr[:1200]}")


# --- reading LLVM's own output ------------------------------------------

def parse_opcode_enum(text):
    """The instruction opcode enum from --gen-instr-info."""
    match = re.search(r"enum\s*\{(.*?)\n\s*\};", text, re.S)
    if not match:
        raise SystemExit("no opcode enum in gen-instr-info output")
    opcodes = {}
    for name, value in re.findall(r"(\w+)\s*=\s*(\d+)", match.group(1)):
        opcodes[name] = int(value)
    return opcodes


def parse_operand_slots(text):
    """Per instruction, which MCInst slot holds which named operand.

    Read out of `--gen-emitter`'s switch, where each `MI.getOperand(N)` is
    preceded by `// op: NAME`. This is LLVM stating its own operand order, so
    the gate does not have to assume the one the emitter intended.
    """
    slots = {}
    # LLVM groups instructions whose operand layouts are identical under
    # fall-through case labels, so a group's operands must be recorded for
    # every label of it, not just the last.
    group = []
    recorded = False
    pending = None
    for raw in text.splitlines():
        line = raw.strip()
        # The file repeats the switch under GET_OPERAND_BIT_OFFSET; one copy
        # is enough and the second is compiled out of the harness anyway.
        if line.startswith("#ifdef GET_OPERAND_BIT_OFFSET"):
            break
        # A group ends at its `break;` -- including a group that encodes no
        # operands at all, which is why the terminator is the delimiter and
        # "did it record anything" is not. Instructions with no operands do
        # get a `{ break; }` case of their own.
        if line == "break;":
            group, recorded = [], False
            continue
        case = re.match(r"case\s+\w+::(\w+):", line)
        if case:
            group.append(case.group(1))
            slots.setdefault(case.group(1), {})
            continue
        comment = re.match(r"//\s*op:\s*(\w+)", line)
        if comment:
            pending = comment.group(1)
            continue
        operand = re.search(r"MI\.getOperand\((\d+)\)", line)
        if operand and group and pending is not None:
            for name in group:
                slots[name][pending] = int(operand.group(1))
            recorded = True
            pending = None
    return slots


# --- the harness ---------------------------------------------------------

HARNESS = r"""
// Compiles LLVM's generated encoder against AXIS's, and runs both.
// The MC types are stubs on purpose: what is under test is the generated
// table and its shifts, not LLVM's containers.
#include <cstdint>
#include <cstdio>
#include <cstring>
#include <vector>
#include <string>

namespace llvm {
class MCOperand {
 public:
  uint64_t V = 0;
  uint64_t getReg() const { return V; }
  int64_t getImm() const { return (int64_t)V; }
  bool isReg() const { return true; }
  bool isImm() const { return true; }
};
class MCInst {
 public:
  unsigned Op = 0;
  std::vector<MCOperand> Ops;
  unsigned getOpcode() const { return Op; }
  const MCOperand &getOperand(unsigned i) const { return Ops[i]; }
  unsigned getNumOperands() const { return (unsigned)Ops.size(); }
};
class MCSubtargetInfo {};
class MCFixup {};
template <typename T> using SmallVectorImpl = std::vector<T>;
class APInt {
 public:
  uint64_t V = 0;
  APInt() {}
  APInt(unsigned, uint64_t v) : V(v) {}
  APInt &operator=(uint64_t v) { V = v; return *this; }
};
}  // namespace llvm
using namespace llvm;

#include "axis_encode.h"

namespace TARGETNS { enum { OPCODE_ENUM }; }

class TARGETNSMCCodeEmitter {
 public:
  uint64_t getMachineOpValue(const MCInst &, const MCOperand &MO,
                             SmallVectorImpl<MCFixup> &,
                             const MCSubtargetInfo &) const {
    return MO.V;
  }
  void reportUnsupportedInst(const MCInst &) const { unsupported = true; }
  mutable bool unsupported = false;
  // Defined by LLVM's generated code below, exactly as a real backend's
  // .cpp includes it at namespace scope.
  uint64_t getBinaryCodeForInstr(const MCInst &MI,
                                 SmallVectorImpl<MCFixup> &Fixups,
                                 const MCSubtargetInfo &STI) const;
};

#include "axis_emitter.inc"

struct Case {
  size_t axis_index;      // row in AXIS's encode table
  unsigned llvm_opcode;
  unsigned num_operands;  // MCInst operand count
  int slots[16];          // slots[axis operand index] = MCInst slot, -1 none
  int widths[16];         // encoded width of each operand, 0 if unencoded
  int operand_count;
};

static const Case CASES[] = { CASE_TABLE };
static const size_t CASE_COUNT = sizeof(CASES) / sizeof(CASES[0]);

int main() {
  TARGETNSMCCodeEmitter emitter;
  std::vector<MCFixup> fixups;
  MCSubtargetInfo sti;
  uint64_t seed = SEED_VALUE;
  auto next = [&]() {
    seed = seed * 6364136223846793005ULL + 1442695040888963407ULL;
    return (uint32_t)(seed >> 33);
  };
  long compared = 0, mismatched = 0, never = 0;
  for (size_t c = 0; c < CASE_COUNT; ++c) {
    const Case &kase = CASES[c];
    long here = 0;
    // A refused encode is a decode constraint the drawn values did not meet:
    // ADD_X_SHIFT0 pins its shift to zero, SBFM_W pins N. Uniform draws
    // essentially never satisfy those, so the search is bounded rather than
    // one-shot -- otherwise the gate reports green about instructions it
    // never encoded, which is what it did before this counter existed.
    for (long attempt = 0; attempt < (long)TRIALS * 4096 && here < TRIALS;
         ++attempt) {
      // Half the draws fit the operand's encoded field, half do not.
      // Values that fit are what a caller supplies and what a decode
      // constraint such as a64_shifted_reg can accept -- without them the
      // constrained instructions are never encoded at all. Values that do
      // not fit are what proves the two encoders mask alike.
      const bool fitted = (attempt & 1) == 0;
      uint32_t values[16];
      for (int i = 0; i < kase.operand_count; ++i) {
        uint32_t drawn = next();
        int width = kase.widths[i];
        values[i] = (fitted && width > 0 && width < 32)
                        ? (drawn & ((1u << width) - 1u))
                        : drawn;
      }

      uint32_t axis_insn = 0;
      if (!axis_encode_by_index(kase.axis_index, values, &axis_insn)) continue;
      ++here;

      MCInst inst;
      inst.Op = kase.llvm_opcode;
      inst.Ops.resize(kase.num_operands);
      for (int i = 0; i < kase.operand_count; ++i)
        if (kase.slots[i] >= 0) inst.Ops[kase.slots[i]].V = values[i];

      emitter.unsupported = false;
      uint64_t llvm_insn = emitter.getBinaryCodeForInstr(inst, fixups, sti);
      if (emitter.unsupported) {
        printf("UNSUPPORTED axis_index=%zu\n", kase.axis_index);
        return 2;
      }
      ++compared;
      if ((uint32_t)llvm_insn != axis_insn) {
        ++mismatched;
        if (mismatched <= 5)
          printf("MISMATCH axis_index=%zu axis=0x%08x llvm=0x%08x\n",
                 kase.axis_index, axis_insn, (uint32_t)llvm_insn);
      }
    }
    if (here == 0) {
      ++never;
      printf("NEVER-ENCODED axis_index=%zu\n", kase.axis_index);
    }
  }
  printf("COMPARED %ld MISMATCHED %ld NEVER %ld\n", compared, mismatched, never);
  return (mismatched == 0 && never == 0) ? 0 : 1;
}
"""


def tablegen_ident(value):
    """Mirror of `tablegen_ident` in src/emit/common.rs, then uppercased as
    the target emitter does for def names."""
    out = []
    for ch in value:
        out.append(ch.upper() if ch.isascii() and ch.isalnum() else "_")
    return "".join(out) or "PCE"


def strip_root_type(dag):
    """A pattern's LHS without the value type its root carries, if it has one.

    `(i32 (add ...))` is a value pattern and its type is not compared here; a
    root like `(store ...)` or `(atomic_swap_i32_monotonic ...)` is the node
    itself and stays. Written as one rule rather than a list of node names,
    because the list was wrong three times: store roots, then indexed-store
    roots, then atomic roots were each invisible to this file until someone
    noticed the pattern count and the claimed-once count disagreeing.
    """
    found = re.fullmatch(r"\(i\d+ (.*)\)", dag, re.S)
    return found.group(1) if found else dag


def parse_target_patterns(text):
    """{MNEMONIC: [LHS DAG]} for every `def : Pat<` in the emitted target."""
    out = {}
    for match in re.finditer(r"^def : Pat<(\(.*?\)),\n\s*\((\w+) ",
                             text, re.M | re.S):
        dag, opcode = match.groups()
        out.setdefault(opcode, []).append(strip_root_type(dag))
    return out


def parse_intrinsic_patterns(text):
    """{mnemonic: LHS DAG} for every pattern in `emit-llvm-patterns`.

    The mnemonic is read off the `// <mnemonic> => llvm.axis.<suffix>` line
    the emitter already writes, rather than reconstructed from the intrinsic
    name -- a suffix can come from the description's `intrinsic` field, so
    recomputing it here would be a second copy of a Rust naming rule.
    """
    out = {}
    for match in re.finditer(r"^// (\S+) => llvm\.axis\.\S+\n"
                             r"def : Pat<(.*?),\n\s*\(int_axis_", text, re.M | re.S):
        mnemonic, dag = match.groups()
        # Both files state the root's type and neither compares it here: the
        # target's parser drops it too, because a class's value types and a
        # width are two spellings of the same fact and this check is about the
        # operators.
        out.setdefault(mnemonic, []).append(strip_root_type(dag))
    return out


def normalise_dag(dag):
    """A DAG with its leaves stripped of how they are spelled.

    The two files type a leaf differently on purpose: the intrinsic hints say
    `i64:$rs1`, the target says `GPRRegs:$rs1`. Everything else -- the
    operators, their order, the constants and their types -- must be identical,
    because both come from one `llvm_pattern_dag`.
    """
    # An immediate's predicate is kept, because it is not a spelling: it says
    # which values the instruction can be selected for, and it is the same
    # fact in both files. Stripping it alongside the register classes would
    # have let a target claiming `simm16` agree with a golden `simm12`.
    dag = re.sub(r"(?![su]imm\d+i\d+:)[A-Za-z_][\w]*:\$", "$", dag)
    dag = re.sub(r"\$(\w+)", lambda m: "$" + m.group(1).lower(), dag)
    # `$rn_tied` and `$rn` are one register. The suffix exists only because the
    # target's operand list has to name the input side of a tie -- it is a
    # spelling, like the register class beside it, and not a difference in what
    # the pattern means.
    dag = re.sub(r"\$(\w+)_tied\b", r"$\1", dag)
    return re.sub(r"\s+", " ", dag).strip()


def check_patterns_against_golden(target_text, intrinsic_text):
    """The target's patterns are the ones checked against the golden model.

    `llvm_patterns_check.py` evaluates every DAG in `emit-llvm-patterns`
    against the generated golden model, so those DAGs carry a proof of
    meaning. The target's patterns select real instructions and nothing
    evaluates them -- but they come from the same `llvm_pattern_dag`, so if
    every target DAG is a DAG that file also emits, the proof carries over.

    That "if" is the whole gate. Sharing a function is not evidence: the two
    callers pass different leaf spellings and the target applies four further
    conditions of its own, any of which could have been a transform rather
    than a filter. This checks the conclusion instead of trusting the
    construction.
    """
    target = parse_target_patterns(target_text)
    intrinsic = parse_intrinsic_patterns(intrinsic_text)
    by_upper = {}
    for mnemonic, dags in intrinsic.items():
        key = re.sub(r"[^A-Za-z0-9]", "_", mnemonic).upper()
        by_upper.setdefault(key, []).extend(dags)

    # Every DAG, not one per instruction. A selector gets a pattern per value
    # it encodes, so an instruction has several -- and keying by mnemonic kept
    # only the last of them, which made this compare one arbitrary member of
    # each set against another. It agreed for as long as both files emitted the
    # same list in the same order, and stopped the moment the target dropped a
    # specialisation the intrinsic file kept.
    failures, matched = [], 0
    for opcode, dags in sorted(target.items()):
        golden = by_upper.get(opcode)
        if golden is None:
            failures.append(f"  {opcode}: selects an instruction that "
                            f"emit-llvm-patterns has no pattern for")
            continue
        proven = {normalise_dag(one) for one in golden}
        for dag in dags:
            if normalise_dag(dag) not in proven:
                failures.append(f"  {opcode}: target DAG is not one "
                                f"emit-llvm-patterns proves\n"
                                f"    target: {normalise_dag(dag)}\n"
                                f"    proved: {', '.join(sorted(proven))}")
                continue
            matched += 1

    if failures:
        print(f"FAIL: {len(failures)} target pattern(s) are not the patterns "
              f"llvm_patterns_check.py proves:")
        print("\n".join(failures))
        return None
    # Patterns the intrinsic file emits and the target declines are expected
    # -- the target additionally requires a single result, register operands,
    # no derived operands and a bounded commutation count. Counted, not
    # silent, so the gap cannot widen unnoticed.
    return matched, sum(len(dags) for dags in intrinsic.values()) - matched


def check_pattern_operand_order(text):
    """A Pat's RHS operands must be the instruction's, in the encoded order.

    Selection supplies the RHS operands positionally into `InOperandList`, and
    the encoder differential below proves slot N of that list is AXIS operand
    N. So a RHS in any other order builds an MCInst that encodes correctly and
    computes the wrong thing -- `(sub $rs1, $rs2)` selecting `(SUB $rs2,
    $rs1)` is a subtraction with its operands swapped, which every other gate
    here passes: tblgen sees two operands of the right class, the matcher is
    built, and the bits are those of a valid SUB.

    Reversing the emitted order was injected and no gate in this file noticed.
    That is why this is checked rather than argued: both orders come from one
    iteration over the operands, and "it is the same loop" was exactly the
    reasoning that did not hold.
    """
    ins = {}
    for match in re.finditer(r"^def (\w+) : \w+Inst<\(outs[^)]*\), \(ins([^)]*)\)",
                             text, re.M):
        opcode, operands = match.groups()
        ins[opcode] = re.findall(r"\$(\w+)", operands)

    failures = []
    for match in re.finditer(r"^def : Pat<.*?\n\s*\((\w+)([^)]*)\)>;",
                             text, re.M | re.S):
        opcode, operands = match.groups()
        used = re.findall(r"\$(\w+)", operands)
        expected = ins.get(opcode)
        if expected is None:
            failures.append(f"  {opcode}: pattern selects an instruction "
                            f"this target does not define")
        elif used != expected:
            failures.append(f"  {opcode}: pattern passes {used}, but the "
                            f"instruction's operands are {expected}")
    if failures:
        print(f"FAIL: {len(failures)} pattern(s) supply operands in an order "
              f"the instruction does not have:")
        print("\n".join(failures))
        return False
    return True


def check_state_clobbers(text, lift_entries):
    """Every state an instruction writes must be declared as a `Defs`.

    This is what makes a value pattern on a flag-setting instruction honest.
    `ADDS` computes a sum and writes NZCV; a `Pat` matching only the sum is
    correct *because* the clobber is declared, so the register allocator does
    not keep a live value in a register the instruction destroys. Drop the
    declaration and nothing else in this file notices -- tblgen accepts an
    instruction that lies about what it writes, the encoder differential
    compares bits, and the golden model compares the destination value. That
    was injected and passed every gate here, which is why this exists.

    The two sides are different emitters: `emit-llvm-target` walks the
    behavior's effect locations, `emit-lift-json` publishes the same behavior
    as an effect list. They agree on which states an instruction writes, or one
    of them is wrong about the machine.
    """
    def as_opcode(mnemonic):
        """The mnemonic as `emit-llvm-target` spells its def.

        A TableGen identifier is uppercased, so keying on the raw mnemonic
        silently failed to join for any corpus whose mnemonics are not already
        upper case -- RVV's scalable lanes are `__l0`, and every one of them
        looked like an instruction declaring a clobber it did not have.
        """
        ident = "".join(c if c.isalnum() else "_" for c in mnemonic).upper()
        return ident or "PCE"

    # Keyed by the name the target emits, which for a scalable instruction is
    # the GROUP's -- `VSSUBU_VV_X`, not the lane's `VSSUBU_VV_X__L0`. The lift
    # table is per-lane because executing a scalable instruction *is* its
    # lanes; the target is per-encoding because a lane is not a machine
    # instruction. Keying on the lane name looked up a def that does not exist
    # and reported every scalable state write as absent.
    writes = {}
    for entry in lift_entries:
        states = {effect["state"] for effect in (entry.get("effects") or [])
                  if effect.get("kind") == "setstate" and effect.get("state")}
        if not states:
            continue
        name = entry.get("scalable_origin") or entry["mnemonic"]
        writes.setdefault(as_opcode(name), set()).update(states)

    declared = {}
    for match in re.finditer(r"^def (\w+) : \w+Inst<.*?\n((?:  .*\n)*)", text, re.M):
        opcode, body = match.groups()
        found = re.search(r"^  let Defs = \[([^\]]*)\];", body, re.M)
        declared[opcode] = ({name.strip() for name in found.group(1).split(",")}
                            if found else set())

    def as_def(state):
        ident = "".join(c if c.isalnum() else "_" for c in state).upper()
        return ident or "PCE"

    # Both directions. A missing `Defs` is a silent clobber; a spurious one
    # tells LLVM a register is destroyed when it is not, which costs a live
    # value for nothing. Iterating the *declarations* rather than the writes is
    # what catches the second -- checking only instructions known to write
    # state skips exactly the instructions that should write none.
    failures = []
    for opcode in sorted(declared):
        expected = {as_def(state) for state in writes.get(opcode, set())}
        if declared[opcode] != expected:
            failures.append(f"  {opcode}: declares Defs {sorted(declared[opcode]) or '[]'}, "
                            f"but its behavior writes {sorted(expected) or '[]'}")
    if failures:
        print(f"FAIL: {len(failures)} instruction(s) do not declare the state "
              f"they write:")
        print("\n".join(failures[:10]))
        return None
    return sum(1 for opcode in writes if opcode in declared)


def check_immediate_masks(text, encode_entries):
    """An immediate predicate must accept exactly the values that encode.

    Where a description states no range, the predicate is derived from the
    layout: the encoder writes the operand's bits `[op_lsb, op_lsb + width)`
    into the instruction and the decoder reads them back, so a value with a bit
    set anywhere else is one this instruction cannot represent. RISC-V's `LUI`
    carries bits 31:12 of a 32-bit operand, so `maskimmfffff000i32` accepts the
    immediates whose low twelve bits are clear.

    The golden model cannot check this. It evaluates *values*, and a value with
    an unencodable bit set evaluates the same on both sides -- widening the
    mask was injected and `llvm_patterns_check.py` passed it, because
    encodability is simply not a question it asks. So the mask is checked here,
    against the encode table's own account of where an operand's bits go.
    """
    slices = {}
    for entry in encode_entries:
        for operand in entry.get("operands", []):
            encoding = operand.get("encoding") or {}
            covered = 0
            for piece in encoding.get("slices") or []:
                covered |= ((1 << piece["width"]) - 1) << piece["op_lsb"]
            if covered:
                slices[(entry["mnemonic"], operand["name"])] = covered

    def as_opcode(mnemonic):
        ident = "".join(c if c.isalnum() else "_" for c in mnemonic).upper()
        return ident or "PCE"

    by_opcode = {}
    for (mnemonic, operand), covered in slices.items():
        by_opcode.setdefault(as_opcode(mnemonic), {})[operand.upper()] = covered

    def accepted_bits(predicate):
        """The bits any value this predicate accepts may set, or None to skip.

        A signed predicate is skipped: `simm12` accepts negative values whose
        high bits are set by sign extension, and only the low twelve reach the
        instruction, so a bitwise comparison says nothing about it.
        """
        found = re.fullmatch(r"maskimm([0-9a-f]+)i\d+", predicate)
        if found:
            return int(found.group(1), 16)
        found = re.fullmatch(r"uimm(\d+)i\d+", predicate)
        if found:
            return (1 << int(found.group(1))) - 1
        found = re.fullmatch(r"uimmlt(\d+)i\d+", predicate)
        if found:
            limit = int(found.group(1))
            return 0 if limit <= 1 else (1 << (limit - 1).bit_length()) - 1
        found = re.fullmatch(r"imm((?:\d+_)*\d+)i\d+", predicate)
        if found:
            bits = 0
            for value in found.group(1).split("_"):
                bits |= int(value)
            return bits
        return None

    failures, checked = [], 0
    pattern = re.compile(r"^def (\w+) : \w+Inst<\(outs[^)]*\), \(ins([^)]*)\)", re.M)
    for match in pattern.finditer(text):
        opcode, operands = match.groups()
        for predicate, name in re.findall(r"\b(\w+):\$(\w+)", operands):
            claimed = accepted_bits(predicate)
            if claimed is None:
                continue
            covered = by_opcode.get(opcode, {}).get(name)
            if covered is None:
                continue
            checked += 1
            # Subset, not equality. A predicate may accept *less* than the
            # field holds -- a decode constraint narrows AArch64's two-bit
            # shift field to three values -- and refusing an encodable value
            # only costs a selection. Accepting one the instruction cannot
            # carry is the error, and it is what this catches.
            if claimed & ~covered:
                failures.append(f"  {opcode}.{name}: predicate accepts "
                                f"{claimed:#x}, which is not inside the "
                                f"{covered:#x} the encoding carries")
    if failures:
        print(f"FAIL: {len(failures)} immediate predicate(s) accept values the "
              f"encoding cannot carry:")
        print("\n".join(failures[:10]))
        return None
    return checked


def check_memory_flags(text, lift_entries):
    """An instruction that touches memory must say so.

    Without `mayLoad`/`mayStore` LLVM reads a load as arithmetic: free to
    reorder against other memory, to sink across a barrier, or to delete when
    the result is unused. The operand list carries an address but never says
    the memory is touched, so nothing else in the file implies it -- the whole
    AArch64 seed declared none of this until it was emitted.

    Checked against a different emitter's view of the same behavior:
    `emit-llvm-target` reads the effect summary, `emit-lift-json` publishes it.

    Both directions again. A missing flag lets LLVM move something it must
    not; a spurious one blocks motion that is legal, which costs performance
    silently and is exactly the sort of thing nobody notices.
    """
    expected = {}
    for entry in lift_entries:
        summary = entry.get("effect_summary") or {}
        expected[entry["mnemonic"]] = (
            bool(summary.get("reads_memory")),
            bool(summary.get("writes_memory")),
        )

    def as_opcode(mnemonic):
        ident = "".join(c if c.isalnum() else "_" for c in mnemonic).upper()
        return ident or "PCE"

    by_opcode = {as_opcode(name): flags for name, flags in expected.items()}

    failures, checked = [], 0
    for match in re.finditer(r"^def (\w+) : \w+Inst<.*?\n((?:  .*\n)*)", text, re.M):
        opcode, body = match.groups()
        if opcode not in by_opcode:
            continue
        declared = ("let mayLoad = 1;" in body, "let mayStore = 1;" in body)
        checked += 1
        if declared != by_opcode[opcode]:
            failures.append(f"  {opcode}: declares (mayLoad, mayStore)={declared}, "
                            f"but its behavior is {by_opcode[opcode]}")
    if failures:
        print(f"FAIL: {len(failures)} instruction(s) misdeclare what memory "
              f"they touch:")
        print("\n".join(failures[:10]))
        return None
    return checked


def check_register_writes_are_declared(text, lift_entries):
    """Every register a behavior writes must be an output of the instruction.

    A post-index load writes the loaded value *and* the updated base. The
    second is spelled as an extra output tied to its input -- `(outs $RT, $RN)`
    with `Constraints = "$RN = $RN_tied"` -- and if it were dropped, LLVM would
    believe the base register survives the instruction and keep a stale value
    in it.

    The tie is derived from the operand's declared role, and the write from the
    behavior, so the two could disagree without either being obviously wrong.
    They are joined here.
    """
    def as_opcode(mnemonic):
        ident = "".join(c if c.isalnum() else "_" for c in mnemonic).upper()
        return ident or "PCE"

    writes = {}
    for entry in lift_entries:
        named = {effect["dest"] for effect in (entry.get("effects") or [])
                 if effect.get("kind") == "set" and effect.get("dest")}
        if named:
            writes[as_opcode(entry["mnemonic"])] = {name.upper() for name in named}

    failures, checked, implied = [], 0, 0
    pattern = re.compile(
        r"(?:^// implied, not encoded: (?P<implied>.*)\n)?"
        r"^def (?P<opcode>\w+) : \w+Inst<\(outs(?P<outs>[^)]*)\)", re.M)
    for match in pattern.finditer(text):
        opcode, outs = match.group("opcode"), match.group("outs")
        wanted = writes.get(opcode)
        if wanted is None:
            continue
        declared = {name for name in re.findall(r"\$(\w+)", outs)}
        # A derived operand is implied by the one it derives from, so no field
        # binds it and LLVM has nothing to decode into. `emit-llvm-target`
        # names them above the def rather than dropping them silently, and they
        # are counted here rather than quietly forgiven: an instruction whose
        # write LLVM cannot see is the pair-class gap, not a clean model.
        derived = {name.split("=")[0].strip().upper()
                   for name in (match.group("implied") or "").split(",") if name.strip()}
        checked += 1
        missing = wanted - declared - derived
        implied += len(wanted & derived)
        if missing:
            failures.append(f"  {opcode}: behavior writes {sorted(missing)}, "
                            f"which the instruction does not declare as output(s) "
                            f"{sorted(declared) or '[]'}")
    if failures:
        print(f"FAIL: {len(failures)} instruction(s) write a register they do "
              f"not declare:")
        print("\n".join(failures[:10]))
        return None
    return checked, implied


def predicate_accepts(predicate, value):
    """Whether an immediate predicate admits `value`, or None if unknown."""
    found = re.fullmatch(r"uimmlt(\d+)i\d+", predicate)
    if found:
        return 0 <= value < int(found.group(1))
    found = re.fullmatch(r"uimm(\d+)i\d+", predicate)
    if found:
        return 0 <= value < (1 << int(found.group(1)))
    found = re.fullmatch(r"simm(\d+)i\d+", predicate)
    if found:
        bits = int(found.group(1))
        return -(1 << (bits - 1)) <= value < (1 << (bits - 1))
    found = re.fullmatch(r"maskimm([0-9a-f]+)i\d+", predicate)
    if found:
        return value & ~int(found.group(1), 16) == 0
    found = re.fullmatch(r"imm((?:\d+_)*\d+)i\d+", predicate)
    if found:
        return value in {int(part) for part in found.group(1).split("_")}
    return None


def check_pinned_selectors(text):
    """A literal a pattern supplies must be one its operand can hold.

    A helper that switches on an operand gets one pattern per value of it, and
    the pattern names that value in its RHS: `(ADD_X_SHIFT0 $RN, $RM, (i64 0),
    $IMM6)` is the LSL form. The operand's predicate says which values the
    instruction encodes -- `uimmlt3` for a shift kind, because `a64_shifted_reg`
    permits three and ROR is not among them.

    Emitting the ROR variant anyway was injected and passed everything else:
    the golden model evaluates the rotate quite happily, because it models what
    the *semantics* computes and not what the *decoder* accepts. Joining the
    literal to its own operand's predicate is what catches it, and it works
    because the predicate was already narrowed by that same constraint.
    """
    ins = {}
    for match in re.finditer(r"^def (\w+) : \w+Inst<\(outs[^)]*\), \(ins([^)]*)\)",
                             text, re.M):
        opcode, operands = match.groups()
        ins[opcode] = [(predicate, name) for predicate, name
                       in re.findall(r"\b(\w+):\$(\w+)", operands)]

    failures, checked = [], 0
    for match in re.finditer(r"^def : Pat<.*?\n\s*\((\w+)([^)]*(?:\([^)]*\)[^)]*)*)\)>;",
                             text, re.M | re.S):
        opcode, arguments = match.groups()
        slots = ins.get(opcode)
        if slots is None:
            continue
        # Positional: the RHS supplies the instruction's inputs in order.
        supplied = re.findall(r"\(i\d+ (-?\d+)\)|\b\w+:\$(\w+)", arguments)
        for index, (literal, _name) in enumerate(supplied):
            if not literal or index >= len(slots):
                continue
            predicate, operand = slots[index]
            verdict = predicate_accepts(predicate, int(literal))
            if verdict is None:
                continue
            checked += 1
            if not verdict:
                failures.append(f"  {opcode}: supplies {literal} for ${operand}, "
                                f"which {predicate} does not accept")
    if failures:
        print(f"FAIL: {len(failures)} pattern(s) pin an operand to a value it "
              f"cannot hold:")
        print("\n".join(failures[:10]))
        return None
    return checked


def check_no_pattern_claimed_twice(text):
    """No two instructions may have the same pattern left-hand side.

    Two `Pat`s with one LHS are not a pattern each. TableGen takes one of them
    by an ordering rule the description has never said anything about -- and
    AArch64's `ADD` and `ADDS` reduce to the same expression, so if it took the
    flag-setting form then every plain add in the program would destroy NZCV.

    Neither differential can see this. Both DAGs are correct, and each is
    evaluated against the golden model on its own; the question is only asked
    by comparing one instruction's pattern with another's. The emitter drops
    such a pair and names both, so this is the gate that says it stayed
    dropped.

    Returns the number of distinct left-hand sides, or None on a violation.
    """
    claims = {}
    # A value pattern's root is `(iN ...)`; a store's is `(store ...)` or
    # `(truncstoreiN ...)`, because a store has no result to type. Both are
    # claims on a left-hand side and both belong in this count.
    for match in re.finditer(r"^def : Pat<(\(.*?\)),\n\s*\((\w+) ",
                             text, re.M | re.S):
        lhs, opcode = match.groups()
        claims.setdefault(lhs, []).append(opcode)
    clashes = {lhs: names for lhs, names in claims.items() if len(names) > 1}
    if clashes:
        for lhs, names in sorted(clashes.items())[:10]:
            print(f"  {', '.join(names)} all claim {lhs}")
        print(f"FAIL: {len(clashes)} pattern(s) claimed by more than one "
              f"instruction")
        return None
    return len(claims)


def decline_census(text):
    """What the target declined, by reason, most common first.

    A gate that only says PASS is silent about the far larger set of
    instructions it emitted nothing for, and twice now a claim has rested on a
    check that was declining the very thing being claimed -- the load patterns
    the golden check never evaluated, and 62 AArch64 patterns that were
    duplicates of each other. Both were found by reading declines rather than
    by reading a green line.

    So the declines are printed, with their counts, on every run. Numbers in a
    reason are folded away so that "a 12-bit load" and "an 8-bit load" are one
    cause and not two.
    """
    reasons = {}
    for line in text.splitlines():
        found = re.fullmatch(r"// \S+: (.*); no pattern", line)
        if not found:
            continue
        reason = found.group(1)
        # A collision note carries the whole left-hand side, which makes every
        # one of them a distinct "reason" and buries the count. The cause is
        # the collision, not the DAG.
        reason = re.sub(r"^\(.*\) is (also .*|.*'s pattern, which .*)$",
                        r"claimed by another instruction, which \1",
                        reason)
        reason = re.sub(r"claimed by another instruction, which also .*",
                        "claimed by another instruction too", reason)
        reason = re.sub(r"claimed by another instruction, which .*'s pattern, which (.*)",
                        r"claimed by an instruction that \1", reason)
        reason = re.sub(r"`[^`]*`", "X", reason)
        reason = re.sub(r"\d+", "N", reason)
        reasons[reason] = reasons.get(reason, 0) + 1
    return sorted(reasons.items(), key=lambda pair: (-pair[1], pair[0]))


def tablegen_reg(class_name: str, index: int) -> str:
    """The def name `emit-llvm-target` gives one register of a class.

    Derived here rather than read out of the target file, because that is the
    point: the declaration says `rv_gpr 10` and this gate has to know which
    LLVM register that is in order to compare the two sides at all.
    """
    ident = "".join(ch if ch.isalnum() else "_" for ch in class_name)
    return f"{ident.upper()}{index}"


def calling_convention_bodies(generated: str) -> dict[str, list[str]]:
    """Every generated convention, by name, with the registers it assigns.

    Parsed by walking the *definitions* -- `...State) {` -- rather than
    searching for one name at a time. Two reasons, both of which the first
    version of this got wrong: a forward declaration starts exactly like the
    definition it precedes, and `RetCC_ILP32` contains `CC_ILP32`, so a search
    for either found the other's register list.
    """
    bodies: dict[str, list[str]] = {}
    for match in re.finditer(
            r"static bool (\w+)\(unsigned ValNo[^;{]*?State\) \{(.*?)\n\}",
            generated, re.S):
        registers: list[str] = []
        for reglist in re.findall(
                r"static const MCPhysReg RegList\d+\[\] = \{(.*?)\}",
                match.group(2), re.S):
            registers.extend(re.findall(r"::(\w+)", reglist))
        bodies[match.group(1)] = registers
    return bodies


def check_calling_conventions(generated: str, abis: list[dict]) -> int | None:
    """LLVM's generated convention assigns the registers the ABI declared.

    L4's differential, and the same shape as L2's: one side is the ABI a
    description declares, the other is C++ that LLVM's own TableGen wrote from
    the `.td` this repo emits. They share no code. An emitter that reordered an
    argument list, dropped a register from it, or wrote the callee-saved set
    into the argument slot would agree with itself and disagree here.

    Order is checked, not just membership. An argument list is an ordered thing
    -- `a0` first is what makes it `a0` -- and a convention with the same
    registers in a different order is a different convention that passes every
    comparison of sets.
    """
    bodies = calling_convention_bodies(generated)
    checked = 0
    for abi in abis:
        name = "".join(ch if ch.isalnum() else "_" for ch in abi["name"]).upper()
        for prefix, role in (("CC", "arguments"), ("RetCC", "returns")):
            declared = [tablegen_reg(klass, index) for klass, index in abi[role]]
            found = bodies.get(f"{prefix}_{name}")
            if found is None:
                if declared:
                    print(f"FAIL: LLVM generated no {prefix}_{name}, but the abi "
                          f"declares {len(declared)} {role}")
                    return None
                continue
            if found != declared:
                print(f"FAIL: {prefix}_{name} assigns {found}, the abi declares "
                      f"{declared}")
                return None
            checked += len(declared)
    return checked


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source")
    parser.add_argument("--trials", type=int, default=64)
    parser.add_argument("--seed", type=int, default=20260824)
    parser.add_argument("--keep", help="work in this directory instead of a temp one")
    parser.add_argument("--skip-isel", action="store_true",
                        help="skip --gen-dag-isel (minutes on a large corpus)")
    args = parser.parse_args()

    skip_isel = args.skip_isel
    tb, inc = find_tblgen(), find_include()
    compiler = shutil.which("clang++") or shutil.which("g++")
    if tb is None or inc is None or compiler is None:
        missing = []
        if tb is None:
            missing.append("llvm-tblgen")
        if inc is None:
            missing.append("LLVM include dir with llvm/Target/Target.td")
        if compiler is None:
            missing.append("a C++ compiler")
        print(f"SKIP: {', '.join(missing)} not found")
        return 0

    source = Path(args.source)
    import contextlib
    holder = (contextlib.nullcontext(args.keep) if args.keep
              else tempfile.TemporaryDirectory())
    with holder as tmp:
        work = Path(tmp)
        td = work / "target.td"
        axis(["emit-llvm-target", str(source)], td)
        axis(["emit-encode-c", str(source)], work / "axis_encode.h")
        axis(["emit-encode-json", str(source)], work / "encode.json")

        tablegen(tb, inc, td, "gen-emitter", work / "axis_emitter.inc")
        tablegen(tb, inc, td, "gen-instr-info", work / "instrinfo.inc")
        # The other generators are the rest of the target LLVM would build.
        # They are run for their exit codes: --gen-disassembler in particular
        # fails on two instructions that claim one bit pattern, which is how
        # the lane instantiations and the definedness masks first showed up.
        for kind in ("gen-register-info", "gen-disassembler", "gen-asm-writer"):
            tablegen(tb, inc, td, kind, work / f"{kind}.inc")
        # L4. The calling convention, read back by the generator that would
        # build it in a real backend. A convention naming a register that does
        # not exist, or a class with no registers, fails here.
        tablegen(tb, inc, td, "gen-callingconv", work / "callingconv.inc")

        # Instruction selection. The target's patterns select its own
        # instructions, so --gen-dag-isel builds a matcher from them; a
        # pattern that named an operand the instruction does not have, or
        # typed one wrongly, fails here.
        text = td.read_text()
        pattern_count = len(re.findall(r"^def : Pat<", text, re.M))
        isel = None
        if not skip_isel:
            tablegen(tb, inc, td, "gen-dag-isel", work / "isel.inc")
            isel = (work / "isel.inc").read_text()
            # A matcher is emitted even with no patterns at all -- LLVM's own
            # entries are always there -- so counting nodes proves nothing.
            # What proves it is the matcher naming this target's instructions.
            selected = set(re.findall(r"TARGET_VAL\((?:\w+)::(\w+)\)", isel))
            selected &= set(re.findall(r"^def (\w+) : \w+Inst<", text, re.M))
            if pattern_count and not selected:
                print(f"FAIL: {pattern_count} patterns emitted but the matcher "
                      f"selects none of this target's instructions")
                return 1
            print(f"ISel: {pattern_count} patterns, "
                  f"{len(selected)} instructions selectable")

        # The patterns tblgen just accepted are type-correct. Whether they
        # mean what AXIS says the instruction means is a separate question,
        # and it is already answered for `emit-llvm-patterns` by
        # `llvm_patterns_check.py` against the golden model. Join the two.
        axis(["emit-llvm-patterns", str(source)], work / "patterns.td")
        agreement = check_patterns_against_golden(
            text, (work / "patterns.td").read_text())
        if agreement is None:
            return 1
        matched, declined = agreement
        if not check_pattern_operand_order(text):
            return 1

        # State clobbers, against a different emitter's view of the same
        # behavior. See `check_state_clobbers` for why this is not redundant
        # with anything else here.
        axis(["emit-lift-json", str(source)], work / "lift.json")
        lift = json.loads((work / "lift.json").read_text())
        clobbers = check_state_clobbers(
            text, lift["instructions"] if isinstance(lift, dict) else lift)
        if clobbers is None:
            return 1
        print(f"State: {clobbers} instruction(s) declare the state they write")

        lift_entries = lift["instructions"] if isinstance(lift, dict) else lift
        touched = check_memory_flags(text, lift_entries)
        if touched is None:
            return 1
        declared_writes = check_register_writes_are_declared(text, lift_entries)
        if declared_writes is None:
            return 1
        written, implied = declared_writes
        print(f"Memory: {touched} instruction(s) declare what they touch; "
              f"{written} declare every register they write")
        if implied:
            print(f"  ({implied} write(s) are to derived operands LLVM cannot "
                  f"see -- the pair class named in docs/llvm_backend.md)")

        print(f"ISel meaning: {matched} pattern(s) identical to the "
              f"golden-checked DAG; {declined} declined by the target")

        # L4's differential: LLVM's generated convention against the ABI the
        # description declares. Two sides, no shared code.
        axis(["emit-json", str(source)], work / "manifest.json")
        abis = json.loads((work / "manifest.json").read_text()).get("abis", [])
        if abis:
            assigned = check_calling_conventions(
                (work / "callingconv.inc").read_text(), abis)
            if assigned is None:
                return 1
            print(f"ABI: {len(abis)} convention(s), {assigned} register "
                  f"assignment(s) agree with the declaration")

        opcodes = parse_opcode_enum((work / "instrinfo.inc").read_text())
        slots = parse_operand_slots((work / "axis_emitter.inc").read_text())

        table = json.loads((work / "encode.json").read_text())
        entries = table["instructions"] if isinstance(table, dict) else table

        # Immediate predicates, against the encode table's own account of
        # where an operand's bits go. See `check_immediate_masks`.
        masks = check_immediate_masks(text, entries)
        if masks is None:
            return 1
        pinned = check_pinned_selectors(text)
        if pinned is None:
            return 1
        distinct = check_no_pattern_claimed_twice(text)
        if distinct is None:
            return 1
        if distinct:
            print(f"Patterns: {distinct} left-hand side(s), each claimed once")
        census = decline_census(text)
        if census:
            total = sum(count for _, count in census)
            print(f"Declines: {total} instruction(s) with no pattern, "
                  f"{len(census)} distinct reason(s)")
            for reason, count in census[:6]:
                print(f"  {count:5d}  {reason}")
            if len(census) > 6:
                rest = sum(count for _, count in census[6:])
                print(f"  {rest:5d}  in {len(census) - 6} further reason(s)")
        if pinned:
            print(f"Selectors: {pinned} pinned value(s) their operand can hold")
        print(f"Immediates: {masks} predicate(s) accept exactly what encodes")

        cases = []
        skipped_unencodable = 0
        skipped_absent = 0
        for index, entry in enumerate(entries):
            if not entry.get("encodable", True):
                skipped_unencodable += 1
                continue
            name = tablegen_ident(entry["mnemonic"]).upper()
            if name not in opcodes or name not in slots:
                # A lane past the first, a definedness mask -- the target
                # emitter declines these by name; see docs/llvm_backend.md.
                skipped_absent += 1
                continue
            operands = entry.get("operands", [])
            if len(operands) > 16:
                skipped_absent += 1
                continue
            mapping = []
            widths = []
            highest = -1
            claimed = set()
            for operand in operands:
                encoding = operand.get("encoding") if isinstance(operand, dict) else None
                slices = (encoding or {}).get("slices") or []
                widths.append(max((s["op_lsb"] + s["width"] for s in slices),
                                  default=0))
                key = tablegen_ident(operand["name"] if isinstance(operand, dict)
                                     else operand)
                slot = slots[name].get(key, -1)
                if slot >= 0:
                    claimed.add(key)
                mapping.append(slot)
                highest = max(highest, slot)
            # Every operand LLVM encodes must have been matched to an AXIS
            # operand. An unmatched one would leave its MCInst slot zero and
            # compare a value neither side chose.
            unmatched = set(slots[name]) - claimed
            if unmatched:
                print(f"FAIL: {name}: LLVM encodes operands AXIS did not "
                      f"supply: {sorted(unmatched)}")
                return 1
            cases.append({
                "axis_index": index,
                "opcode": opcodes[name],
                "num_operands": highest + 1,
                "slots": mapping,
                "widths": widths,
                "count": len(operands),
            })

        if not cases:
            print("FAIL: no instruction was comparable")
            return 1

        target = re.search(r'let Namespace = "(\w+)"', td.read_text()).group(1)
        case_rows = ",\n  ".join(
            "{{ {index}, {opcode}, {num}, {{{slots}}}, {{{widths}}}, {count} }}".format(
                index=case["axis_index"], opcode=case["opcode"],
                num=case["num_operands"],
                slots=", ".join(str(slot) for slot in case["slots"]) or "0",
                widths=", ".join(str(w) for w in case["widths"]) or "0",
                count=case["count"])
            for case in cases)

        harness = (HARNESS
                   .replace("TARGETNS", target)
                   .replace("OPCODE_ENUM", ", ".join(
                       f"{name} = {value}" for name, value in
                       sorted(opcodes.items(), key=lambda kv: kv[1])))
                   .replace("CASE_TABLE", case_rows)
                   .replace("SEED_VALUE", str(args.seed))
                   .replace("TRIALS", str(args.trials)))
        (work / "harness.cpp").write_text(harness)

        build = run([compiler, "-std=c++17", "-O1", "-o", str(work / "harness"),
                     str(work / "harness.cpp"), "-I", str(work)])
        if build.returncode != 0:
            print("FAIL: harness did not compile")
            print(build.stderr[:2000])
            return 1

        result = run([str(work / "harness")])
        print(result.stdout.strip())
        if result.returncode != 0:
            print(f"FAIL: harness exit {result.returncode}")
            if result.stderr.strip():
                print(result.stderr[:800])
            return 1

        print(f"instructions compared: {len(cases)}; "
              f"not encodable: {skipped_unencodable}; "
              f"not in target (lane/mask/derived): {skipped_absent}")
        print("LLVM generated encoder == AXIS encoder: PASS")
        return 0


if __name__ == "__main__":
    sys.exit(main())
