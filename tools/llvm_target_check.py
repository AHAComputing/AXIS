#!/usr/bin/env python3
"""Check that the generated LLVM target encodes what AXIS says it encodes.

`emit-llvm-target` emits a self-contained LLVM target. `llvm-tblgen` accepting
it proves it parses and type-checks -- which is what `tablegen_validate.py`
proves about the intrinsics, and it is not evidence about meaning. The same
trap the ISel patterns were in until `llvm_patterns_check.py`.

So this gate runs LLVM's own generators over the target, **compiles the encoder
they produce**, and executes it against AXIS's encoder on the same instructions
and the same operand values. Neither side is written here:

  * one side is `emit-encode-c`, the header-only encode table that
    `roundtrip_check.py` proves round-trips against the decoder;
  * the other is `--gen-emitter`'s `getBinaryCodeForInstr`, generated by LLVM's
    TableGen from the `.td` this repo emits.

They share no code. If they disagree about a single bit, the generated backend
is lying about the machine AXIS describes.

The operand *order* is not assumed either: LLVM's generated switch names the
operand behind every `MI.getOperand(N)` in a comment, so the mapping from an
AXIS operand to an MCInst slot is read out of LLVM's own output.

Skips cleanly when llvm-tblgen, LLVM's include dir, or a C++ compiler is
absent.

Usage:  tools/llvm_target_check.py examples/rv64i.axisl [--trials 64] [--seed N]
"""

