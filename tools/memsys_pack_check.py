#!/usr/bin/env python3
"""A simulator pack runs against the memory system its description declares. Gate.

`memsys_sim_check.py` holds the engine to the reference model with tables
written from the manifest. This holds the engine AS THE PACK CARRIES IT --
tables generated by the Rust emitter, selected with a core, charged through
the simulator's own loads and stores:

  * **selecting a core attaches its system**: a core that is a port of a
    `defmemsys` reports that system and its nodes; one in none reports no
    system, and keeps the single cache it had;
  * **every node counts what the model counts**: an address trace driven
    through `touch_memory` leaves each node's ten counters exactly where the
    reference model leaves them;
  * **a program pays what the model says**: a load/store loop run on a port
    core and on its twin in no system differs in cycles by EXACTLY the sum of
    the model's stalls over the loop's accesses -- each access's cost beyond a
    first-level hit, which is what an instruction's declared latency already
    covers;
  * **two machines joined are coherent with each other**: `cpu1`'s machine
    joins `cpu0`'s system, both run the loop over the SAME lines in lockstep,
    and the shared counters -- forwards, upgrades, invalidations among them --
    are the model's for that interleaving. Each machine's cycles exceed its
    twin's by at least its LOADS' stalls and at most its loads' and stores':
    ⚠️ a stall delays an instruction's completion (arch_packs.md §7d), so a
    load's shows in full through the instruction that reads it, and a store's
    only as far as in-order retirement lets it -- which is the pipeline's
    policy, not the memory system's, and the single-machine loop above, whose
    stores all hit, is where the charge is held exactly.

Usage: tools/memsys_pack_check.py [examples/memory_system.axisl]
"""

from __future__ import annotations

import argparse
import json
import random
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import build_pack  # noqa: E402
from axis_cli import FAILED, PASSED, axis_prefix  # noqa: E402
from memsys_model import Model  # noqa: E402

AXIS_ROOT = Path(__file__).resolve().parent.parent
ENTRY = 0x1000
FIELDS = ("hits", "misses", "writebacks", "evictions", "prefetches", "back_invalidations",
          "row_hits", "row_idle", "row_conflicts", "accesses", "forwards", "invalidations", "upgrades")


# ---- RV-shaped encodings, which the corpus's five instructions use --------------
def i_type(opcode, funct3, rd, rs1, imm):
    return ((imm & 0xFFF) << 20) | (rs1 << 15) | (funct3 << 12) | (rd << 7) | opcode


def s_type(opcode, funct3, rs1, rs2, imm):
    imm &= 0xFFF
    return ((imm >> 5) << 25) | (rs2 << 20) | (rs1 << 15) | (funct3 << 12) | ((imm & 31) << 7) | opcode


def b_type(opcode, funct3, rs1, rs2, imm):
    imm &= 0x1FFF
    return (((imm >> 12) & 1) << 31) | (((imm >> 5) & 0x3F) << 25) | (rs2 << 20) | (rs1 << 15) \
        | (funct3 << 12) | (((imm >> 1) & 0xF) << 8) | (((imm >> 11) & 1) << 7) | opcode


def loop(base: int, count: int, stride: int) -> tuple[list[int], list[tuple[int, bool]]]:
    """x1 = base; x2 = count; do { ld x3,0(x1); sd x3,8(x1); x1 += stride; x2 -= 1 } while x2."""
    words = [
        i_type(0x13, 0, 1, 0, base),           # addi x1, x0, base
        i_type(0x13, 0, 2, 0, count),          # addi x2, x0, count
        i_type(0x03, 3, 3, 1, 0),              # ld   x3, 0(x1)
        s_type(0x23, 3, 1, 3, 8),              # sd   x3, 8(x1)
        i_type(0x13, 0, 1, 1, stride),         # addi x1, x1, stride
        i_type(0x13, 0, 2, 2, -1),             # addi x2, x2, -1
        b_type(0x63, 1, 2, 0, -16),            # bne  x2, x0, ld
    ]
    accesses = []
    for k in range(count):
        accesses += [(base + k * stride, False), (base + k * stride + 8, True)]
    return words, accesses


HARNESS = r"""
#include <stdio.h>
#include <string.h>
#include "axis_pack.h"
extern const axis_sim_pack *%(sim)s(void);
static const axis_sim_pack *S;
#define IMAGE (1 << 16)
static uint8_t CODE[IMAGE];
static uint64_t rd(void *c, uint64_t a, uint32_t w) { (void)c; (void)a; (void)w; return 0; }
static void wr(void *c, uint64_t a, uint64_t v, uint32_t w) { (void)c; (void)a; (void)v; (void)w; }
static uint32_t fetch(void *c, uint64_t pc, int32_t *ok) {
  (void)c; *ok = pc + 4 <= IMAGE && pc >= %(entry)d && pc < %(entry)d + 4 * %(len)d;
  if (!*ok) return 0u;
  uint32_t v = 0; for (uint32_t i = 0; i < 4; ++i) v |= (uint32_t)CODE[pc + i] << (8 * i); return v;
}
static uint64_t on_trap(void *c, const char *cause, uint64_t pc, int32_t *stop) { (void)c; (void)cause; *stop = 1; return pc; }
static const uint32_t PROGRAM[] = { %(program)s };
static const uint64_t TRACE[] = { %(trace)s };

static void stats(void *m, const char *tag) {
  int32_t n = S->memsys_node_count(m);
  for (int32_t i = 0; i < n; ++i) {
    uint64_t v[13] = {0};
    int32_t k = S->memsys_stats(m, i, v, 13);
    printf("%%s %%s %%d", tag, S->memsys_node_name(m, i), k);
    for (int32_t j = 0; j < 13; ++j) printf(" %%llu", (unsigned long long)v[j]);
    printf("\n");
  }
}

static unsigned long long run(const char *core) {
  axis_pack_sim_hooks hooks = { rd, wr, fetch, on_trap, NULL, NULL };
  void *m = S->create(&hooks);
  if (!S->select_core(m, core)) { printf("NOCORE %%s\n", core); return 0; }
  S->reset(m, %(entry)du, %(isa)s, NULL, 0);
  S->count_cycles(m, 1);
  unsigned long long steps = 0;
  while (S->step(m) == AXIS_PACK_SIM_RUNNING && steps < 1000000) steps++;
  unsigned long long c = (unsigned long long)S->cycles(m);
  printf("RUN %%s steps %%llu cycles %%llu\n", core, steps, c);
  if (S->memsys_node_count(m)) stats(m, "PROG");
  S->destroy(m);
  return c;
}

static void joined(void) {
  axis_pack_sim_hooks hooks = { rd, wr, fetch, on_trap, NULL, NULL };
  void *a = S->create(&hooks), *b = S->create(&hooks);
  S->select_core(a, "%(port)s"); S->select_core(b, "%(port2)s");
  int32_t joined = S->memsys_join(b, a);
  S->reset(a, %(entry)du, %(isa)s, NULL, 0); S->reset(b, %(entry)du, %(isa)s, NULL, 0);
  S->count_cycles(a, 1); S->count_cycles(b, 1);
  int ra = 1, rb = 1; unsigned long long guard = 0;
  while ((ra || rb) && guard++ < 1000000) {
    if (ra) ra = S->step(a) == AXIS_PACK_SIM_RUNNING;
    if (rb) rb = S->step(b) == AXIS_PACK_SIM_RUNNING;
  }
  printf("JOIN %%d %%llu %%llu\n", joined, (unsigned long long)S->cycles(a), (unsigned long long)S->cycles(b));
  stats(a, "JOINED");
  S->destroy(b);
  S->destroy(a);
}

int main(void) {
  S = %(sim)s();
  if (!S->memsys_name) { printf("NOABI\n"); return 0; }
  for (int32_t i = 0; i < %(len)d; ++i)
    for (uint32_t b = 0; b < 4; ++b) CODE[%(entry)d + 4 * i + b] = (uint8_t)(PROGRAM[i] >> (8 * b));
  axis_pack_sim_hooks hooks = { rd, wr, fetch, on_trap, NULL, NULL };
  void *m = S->create(&hooks);
  S->select_core(m, "%(port)s");
  printf("SYSTEM %%s %%d\n", S->memsys_name(m), S->memsys_node_count(m));
  for (size_t i = 0; i < sizeof TRACE / sizeof TRACE[0]; ++i) S->touch_memory(m, TRACE[i]);
  stats(m, "TRACE");
  S->select_core(m, "%(twin)s");
  printf("TWIN %%s %%d\n", S->memsys_name(m), S->memsys_node_count(m));
  S->destroy(m);
  run("%(port)s");
  run("%(twin)s");
  joined();
  return 0;
}
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("axis_file", nargs="?", type=Path,
                        default=AXIS_ROOT / "examples" / "memory_system.axisl")
    args = parser.parse_args()
    manifest_json = json.loads(subprocess.run([*axis_prefix(), "emit-memsys-json", str(args.axis_file)],
                                              capture_output=True, text=True, check=True,
                                              cwd=AXIS_ROOT).stdout)
    system = manifest_json["systems"][0]
    ports = [n["core"] for n in system["nodes"] if n["core"]]
    port, port2, twin = ports[0], ports[1], "solo"
    rng = random.Random(7)
    trace = ([k * 64 for k in range(2000)] + [rng.randrange(0, 1 << 20, 8) for _ in range(3000)]
             + [(k * 8192 * 32) % (1 << 26) for k in range(64)])
    words, accesses = loop(0x4000, 600, 1088)
    failures: list[str] = []
    with tempfile.TemporaryDirectory(prefix="axis_mspack_") as work:
        work = Path(work)
        pack = build_pack.build(args.axis_file, work / "packs", only={"sim", "exec", "lift"})
        name = pack["name"]
        root = work / "packs" / name
        isa = json.loads(subprocess.run([*axis_prefix(), "emit-json", str(args.axis_file)], capture_output=True,
                                        text=True, check=True, cwd=AXIS_ROOT).stdout)["isas"][0]["name"]
        source = HARNESS % {"sim": pack["libraries"]["sim"]["entry"], "entry": ENTRY, "len": len(words),
                            "program": ", ".join(f"{w}u" for w in words),
                            "trace": ", ".join(f"{a}ull" for a in trace), "port": port, "port2": port2, "twin": twin,
                            "isa": f'"{isa}"'}
        (work / "h.c").write_text(source)
        subprocess.run(["cc", "-std=c11", "-O1", "-I", str(root / "include"), "-o", str(work / "h"),
                        str(work / "h.c"), str(root / "lib" / pack["libraries"]["sim"]["static"]),
                        str(root / "lib" / pack["libraries"]["exec"]["static"])], check=True, capture_output=True)
        out = subprocess.run([str(work / "h")], capture_output=True, text=True, check=True).stdout.splitlines()

    said = {line.split()[0]: line.split()[1:] for line in out if line.split()[0] in ("SYSTEM", "TWIN", "NOABI")}
    if "NOABI" in said:
        print("  FAIL the simulator library has no memory-system entry points")
        return FAILED
    if said.get("SYSTEM") != [system["name"], str(len(system["nodes"]))]:
        failures.append(f"selecting `{port}` attached {said.get('SYSTEM')}, not `{system['name']}`")
    if said.get("TWIN") not in ([ "0"], ["", "0"]):
        failures.append(f"selecting `{twin}` left a memory system attached: {said.get('TWIN')}")

    def counters(tag):
        got = {}
        for line in out:
            f = line.split()
            if f[0] == tag:
                got[f[1]] = dict(zip(FIELDS, map(int, f[3:])))
        return got

    model = Model(system)
    p = model.port(port)
    for a in trace:
        model.access(p, a, False)
    want = {n["name"]: {k: getattr(model.stats(i), k) for k in FIELDS} for i, n in enumerate(system["nodes"])}
    got = counters("TRACE")
    for node, fields in want.items():
        if got.get(node) != fields:
            diff = {k: (got.get(node, {}).get(k), v) for k, v in fields.items() if got.get(node, {}).get(k) != v}
            failures.append(f"trace: node `{node}` counters (pack, model) differ: {diff}")

    runs = {line.split()[1]: (int(line.split()[3]), int(line.split()[5])) for line in out if line.startswith("RUN ")}
    model = Model(system)
    p = model.port(port)
    hit = next(n for n in system["nodes"] if n["core"] == port)["latency_cycles"]
    stall = sum(max(model.access(p, a, w) - hit, 0) for a, w in accesses)
    if port not in runs or twin not in runs:
        failures.append(f"the program did not run on both cores: {runs}")
    else:
        (ps, pc), (ts, tc) = runs[port], runs[twin]
        if ps != ts or ps < len(accesses):
            failures.append(f"the loop ran {ps} and {ts} steps; it should run the same, past {len(accesses)} accesses")
        elif pc - tc != stall:
            failures.append(f"`{port}` took {pc} cycles and `{twin}` {tc}: the memory system charged {pc - tc}, "
                            f"the model says {stall}")
        prog = counters("PROG")
        want = {n["name"]: {k: getattr(model.stats(i), k) for k in FIELDS} for i, n in enumerate(system["nodes"])}
        for node, fields in want.items():
            if prog.get(node) != fields:
                failures.append(f"program: node `{node}` counters differ from the model's")
    # The joined run: both machines' accesses in lockstep order, one model.
    join = next((line.split() for line in out if line.startswith("JOIN ")), None)
    model = Model(system)
    p0, p1 = model.port(port), model.port(port2)
    shares, loads = [0, 0], [0, 0]
    for a, w in accesses:
        for k, p in enumerate((p0, p1)):
            s = max(model.access(p, a, w) - hit, 0)
            shares[k] += s
            loads[k] += 0 if w else s
    if join is None or join[1] != "1":
        failures.append(f"`{port2}`'s machine could not join `{port}`'s memory system: {join}")
    elif twin in runs:
        tc = runs[twin][1]
        for who, got, share, load in ((port, int(join[2]), shares[0], loads[0]),
                                      (port2, int(join[3]), shares[1], loads[1])):
            if not load <= got - tc <= share:
                failures.append(f"joined: `{who}` took {got} cycles, its twin {tc}: charged {got - tc}, "
                                f"outside the model's [{load} (loads), {share} (loads and stores)]")
        joined = counters("JOINED")
        want = {n["name"]: {k: getattr(model.stats(i), k) for k in FIELDS} for i, n in enumerate(system["nodes"])}
        for node, fields in want.items():
            if joined.get(node) != fields:
                diff = {k: (joined.get(node, {}).get(k), v) for k, v in fields.items() if joined.get(node, {}).get(k) != v}
                failures.append(f"joined: node `{node}` counters (pack, model) differ: {diff}")
        traffic = sum(want[n]["forwards"] + want[n]["upgrades"] + want[n]["invalidations"] for n in want)
        if traffic == 0 and system["coherence"]["protocol"] != "none":
            failures.append("the joined run made no coherence traffic; it is not exercising the protocol")
        if model.violations:
            failures.append(f"the model saw {model.violations} single-writer violations in the joined run")
    # ⚠️ Vacuity: a memory system that charged nothing would agree with a
    # model that charged nothing.
    if stall == 0:
        failures.append("the loop's accesses cost the model nothing; it is not exercising the hierarchy")

    for line in failures:
        print(f"  FAIL {line}")
    print(f"  `{port}` attached `{system['name']}`; {len(trace)} traced accesses and a {len(accesses)}-access "
          f"loop compared with the model; the loop's memory cost {stall} cycles alone, "
          f"and {loads[0]}..{shares[0]} and {loads[1]}..{shares[1]} (loads..all) on two joined machines")
    verdict = "PASS" if not failures else "FAIL"
    print(f"the simulator runs the described memory system: {verdict}")
    return PASSED if not failures else FAILED


if __name__ == "__main__":
    sys.exit(main())
